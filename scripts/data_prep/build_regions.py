"""Build data/regions.yaml (M15): the rest of the world as seven regions.

Each region is the sum of its countries in the 2024 Our World in Data energy and CO2 files and
the IMF World Economic Outlook, the same local copies build_countries.py reads:

    RAW/owid_energy/owid-energy-data.csv
    RAW/owid_co2/owid-co2-data.csv
    RAW/imf/{NGDPD,NGDP_RPCH,LP}.json

    python scripts/data_prep/build_regions.py RAW > data/regions.yaml

The modelled nations (and the EU-27 members) are left out. Countries with CO2 data but no energy
data count toward CO2 only; a region's fossil energy is its fuel CO2 divided by the emission
factor of the countries that have both. Vulnerability is hand-entered (unsourced approximate).
"""

from __future__ import annotations

import csv
import json
import sys
from pathlib import Path

TWH_TO_EJ = 0.0036
YEAR, FROM = "2024", "2019"
FUELS = ("coal", "oil", "gas")
GROWTH_YEARS = [str(y) for y in range(2025, 2031)]

REGIONS = {
    "LAC": dict(
        name="Latin America and Caribbean",
        vuln=1.2,
        iso="ABW AIA ARG ATG BES BHS BLZ BMU BOL BRB CHL COL CRI CUB CUW DMA DOM ECU GRD GTM GUY "
        "HND HTI JAM KNA LCA MSR NIC PAN PER PRY SLV SUR SXM TCA TTO URY VCT VEN VGB",
    ),
    "MEA": dict(
        name="Middle East and North Africa",
        vuln=1.3,
        iso="ARE BHR DZA EGY IRN IRQ ISR JOR KWT LBN LBY MAR OMN PSE QAT SYR TUN YEM",
    ),
    "SSA": dict(
        name="Sub-Saharan Africa",
        vuln=1.8,
        iso="AGO BDI BEN BFA BWA CAF CIV CMR COD COG COM CPV DJI ERI ETH GAB GHA GIN GMB GNB GNQ "
        "KEN LBR LSO MDG MLI MOZ MRT MUS MWI NAM NER RWA SDN SEN SHN SLE SOM SSD STP SWZ SYC "
        "TCD TGO TZA UGA ZMB ZWE",
    ),
    "SEA": dict(
        name="South and Southeast Asia",
        vuln=1.6,
        iso="AFG BGD BTN LKA MDV NPL PAK BRN KHM LAO MMR MYS PHL SGP THA TLS",
    ),
    "EAP": dict(
        name="East Asia and Pacific",
        vuln=0.9,
        iso="HKG KOR MAC MNG PRK TWN CXR COK FJI FSM KIR MHL NCL NIU NRU NZL PLW PNG PYF SLB TON "
        "TUV VUT WLF WSM",
    ),
    "EUR": dict(
        name="Rest of Europe",
        vuln=0.8,
        iso="ALB AND BIH BLR CHE FRO GRL ISL LIE MCO MDA MKD MNE NOR SMR SPM SRB TUR UKR VAT",
    ),
    "CAS": dict(
        name="Central Asia and Caucasus",
        vuln=1.0,
        iso="ARM AZE GEO KAZ KGZ TJK TKM UZB",
    ),
}


def num(row: dict | None, key: str) -> float | None:
    if row is None or not row.get(key):
        return None
    return float(row[key])


def by_iso(path: Path) -> dict[tuple[str, str], dict]:
    with path.open(encoding="utf-8") as fh:
        return {(r["iso_code"], r["year"]): r for r in csv.DictReader(fh) if r["iso_code"]}


def imf(raw: Path, code: str) -> dict:
    return json.loads((raw / "imf" / f"{code}.json").read_text())["values"][code]


def tun(value, note, source=None, unit=None, status="calibrated") -> str:
    parts = [f"value: {value}", f"status: {status}"]
    if source:
        parts.append(f"source: {source}")
    if unit:
        parts.append(f"unit: {unit}")
    parts.append(f'note: "{note}"')
    return "{" + ", ".join(parts) + "}"


def clean_twh(e: dict | None, factor: float) -> float | None:
    """Low-carbon primary energy (TWh): the Energy Institute figure, or low-carbon electricity x
    the world substitution factor where there is no fuel breakdown."""
    low = num(e, "low_carbon_consumption")
    if low is not None:
        return low
    elec = num(e, "low_carbon_electricity")
    return elec * factor if elec is not None else None


def main(raw: Path) -> None:
    energy = by_iso(raw / "owid_energy" / "owid-energy-data.csv")
    co2 = by_iso(raw / "owid_co2" / "owid-co2-data.csv")
    with (raw / "owid_energy" / "owid-energy-data.csv").open(encoding="utf-8") as fh:
        world = {r["year"]: r for r in csv.DictReader(fh) if r["country"] == "World"}
    with (raw / "owid_co2" / "owid-co2-data.csv").open(encoding="utf-8") as fh:
        wco2 = {r["year"]: r for r in csv.DictReader(fh) if r["country"] == "World"}
    factor = num(world[YEAR], "low_carbon_consumption") / num(world[YEAR], "low_carbon_electricity")
    world_ef = sum(num(wco2[YEAR], f"{f}_co2") for f in FUELS) / (
        num(world[YEAR], "fossil_fuel_consumption") * TWH_TO_EJ
    )
    gdp, growth, pop = imf(raw, "NGDPD"), imf(raw, "NGDP_RPCH"), imf(raw, "LP")
    out = [
        "# The rest of the world as seven regions (M15). Generated by",
        "# scripts/data_prep/build_regions.py from 2024 Our World in Data energy and CO2 data and",
        "# the IMF World Economic Outlook; see data/SOURCES.md. Regions exclude the modelled",
        "# nations and the EU-27.",
        "",
        "regions:",
    ]
    for rid, spec in REGIONS.items():
        codes = spec["iso"].split()
        t = dict.fromkeys(("gdp", "g_w", "g_gdp", "pop", "prod", "co2_e", "fossil_e"), 0.0)
        co2_y = {YEAR: 0.0, FROM: 0.0}
        clean_y = {YEAR: 0.0, FROM: 0.0}
        for iso in codes:
            for y in (YEAR, FROM):
                c = co2.get((iso, y))
                fuel = sum(num(c, f"{f}_co2") or 0.0 for f in FUELS)
                co2_y[y] += fuel
                clean_y[y] += clean_twh(energy.get((iso, y)), factor) or 0.0
            e = energy.get((iso, YEAR))
            fossil = num(e, "fossil_fuel_consumption")
            if fossil:
                c = co2.get((iso, YEAR))
                t["co2_e"] += sum(num(c, f"{f}_co2") or 0.0 for f in FUELS)
                t["fossil_e"] += fossil * TWH_TO_EJ
            for f in FUELS:
                t["prod"] += num(e, f"{f}_production") or 0.0
            g = gdp.get(iso, {}).get("2025")
            if g:
                t["gdp"] += g
                rates = [growth.get(iso, {}).get(y) for y in GROWTH_YEARS]
                if all(r is not None for r in rates):
                    t["g_w"] += g
                    t["g_gdp"] += g * sum(rates) / len(rates)
            p = pop.get(iso, {}).get("2025")
            if p:
                t["pop"] += p
        ef = t["co2_e"] / t["fossil_e"] if t["fossil_e"] > 0 else world_ef
        fossil = {y: co2_y[y] / ef for y in co2_y}
        clean = {y: clean_y[y] * TWH_TO_EJ for y in clean_y}
        d_clean, d_fossil = clean[YEAR] - clean[FROM], fossil[YEAR] - fossil[FROM]
        added = d_clean / (d_clean + d_fossil) if d_clean + d_fossil > 0 else 0.9
        clean_add = min(0.9, max(0.1, added))
        ef_note = (
            "Fuel CO2 per EJ of fossil energy, 2024, countries with a fuel breakdown."
            if t["fossil_e"] > 0
            else "No fuel breakdown in the region: world average."
        )
        out += [
            f"  {rid}:",
            f'    name: "{spec["name"]}"',
            f"    countries: [{', '.join(codes)}]",
            "    gdp: "
            + tun(
                round(t["gdp"] / 1000, 3), "Sum of 2025 GDP, current USD.", "imf_weo", "T$"
            ),  # fmt: skip
            "    growth: "
            + tun(
                round(t["g_gdp"] / t["g_w"] / 100, 4),
                "GDP-weighted mean real growth 2025-2030.",
                "imf_weo",
            ),  # fmt: skip
            "    population: "
            + tun(round(t["pop"], 1), "Sum of 2025 population.", "imf_weo", "million"),  # fmt: skip
            "    co2: "
            + tun(
                round(co2_y[YEAR], 1), "Coal, oil and gas CO2, 2024.", "gcb", "MtCO2/yr"
            ),  # fmt: skip
            "    fossil_ef: "
            + tun(round(ef, 2), ef_note, "energy_institute", "MtCO2/EJ"),  # fmt: skip
            "    clean: "
            + tun(
                round(clean[YEAR], 3),
                "Low-carbon primary energy (substitution "
                "method), 2024; low-carbon electricity x the world substitution "
                "factor where there is no fuel breakdown.",
                "energy_institute",
                "EJ/yr",
            ),  # fmt: skip
            "    fossil: "
            + tun(
                round(fossil[YEAR], 3),
                "Fossil primary energy, 2024: fuel CO2 / fossil_ef.",
                "energy_institute",
                "EJ/yr",
            ),  # fmt: skip
            "    clean_additions: "
            + tun(
                round(clean_add, 3),
                "Low-carbon share of the rise in energy use 2019-2024, clipped to 0.1-0.9.",
                "energy_institute",
            ),  # fmt: skip
            "    fossil_production: "
            + tun(
                round(t["prod"] * TWH_TO_EJ, 3),
                "Coal, oil and gas production, 2024 (countries with a fuel breakdown).",
                "energy_institute",
                "EJ/yr",
            ),  # fmt: skip
            "    vulnerability: "
            + tun(
                spec["vuln"],
                "Unsourced approximate relative index (1 = typical), as for the nations.",
                status="placeholder",
            ),  # fmt: skip
        ]
    print("\n".join(out))


if __name__ == "__main__":
    main(Path(sys.argv[1]))
